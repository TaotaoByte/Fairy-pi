// Build the Fairy mascot bundle.
//
// vendor/fairy-mascot/*.js are taken verbatim from Fairy-DSH
// (fairy-visual/dsh-fairy-visual/src/client). They are CommonJS with only
// internal requires, so instead of pulling in a bundler we wrap each file in a
// tiny module registry and emit one browser-ready IIFE.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const srcDir = path.join(root, 'vendor', 'fairy-mascot');
const outDir = path.join(root, 'src', 'renderer', 'vendor');
const outFile = path.join(outDir, 'fairy-mascot.bundle.js');

const MODULES = [
  'mascot-geometry.js',
  'mascot-eye-svg.js',
  'mascot-effects-svg.js',
  'mascot-style.js',
];

const parts = [];
parts.push('/* Generated by scripts/build-mascot.mjs. Do not edit. */');
parts.push('/* Bundled from Fairy-DSH (Apache-2.0). See ../../NOTICE. */');
parts.push('(function () {');
parts.push('  "use strict";');
parts.push('  var registry = {};');
parts.push('  function define(name, factory) { registry[name] = { factory: factory, exports: {}, loaded: false }; }');
parts.push('  function require(id) {');
parts.push('    var key = String(id).replace(/^\\.\\//, "");');
parts.push('    var mod = registry[key];');
parts.push('    if (!mod) throw new Error("Fairy mascot bundle: unknown module " + id);');
parts.push('    if (!mod.loaded) { mod.loaded = true; mod.factory(mod, require); }');
parts.push('    return mod.exports;');
parts.push('  }');

for (const name of MODULES) {
  const file = path.join(srcDir, name);
  const code = readFileSync(file, 'utf8');
  parts.push(`  define(${JSON.stringify(name)}, function (module, require) {`);
  parts.push(code);
  parts.push('  });');
}

parts.push('  var effects = require("mascot-effects-svg.js");');
parts.push('  window.FairyMascotAssets = Object.freeze({');
parts.push('    CSS: require("mascot-style.js"),');
parts.push('    SVG: require("mascot-eye-svg.js"),');
parts.push('    PULSE_SVG: effects.PULSE_SVG,');
parts.push('    HALO_SVG: effects.HALO_SVG,');
parts.push('  });');
parts.push('})();');
parts.push('');

mkdirSync(outDir, { recursive: true });
writeFileSync(outFile, parts.join('\n'), 'utf8');

// The mascot stylesheet is a plain string export, so emit it as a real file and
// let index.html link it instead of injecting styles at runtime.
const require = createRequire(import.meta.url);
const css = require(path.join(srcDir, 'mascot-style.js'));
const cssFile = path.join(outDir, 'fairy-mascot.css');
writeFileSync(cssFile, `/* Generated by scripts/build-mascot.mjs. Do not edit. */\n/* From Fairy-DSH (Apache-2.0). See ../../NOTICE. */\n${css}\n`, 'utf8');

console.log(`wrote ${outFile} (${MODULES.length} modules)`);
console.log(`wrote ${cssFile} (${css.length} chars)`);
